export const GLYPH_WIDTH = 5;
export const GLYPH_HEIGHT = 7;

export function getGlyph(glyphs: GlyphMap, char: string): readonly number[] | undefined {
  return glyphs[char.toUpperCase()];
}

export function validateGlyphs(glyphs: GlyphMap, charset: string): void {
  for (const ch of new Set(charset)) {
    if (!getGlyph(glyphs, ch)) {
      throw new Error(`Unsupported character in charset: "${ch}"`);
    }
  }
}